// Converts a snarkjs Groth16 verification_key.json into the Rust constants the NEAR pool
// contract embeds (contracts/pool/src/vk.rs).
//
// NEAR's alt_bn128 host functions take little-endian field elements. A G1 point is
// x || y (64 bytes); a G2 point is x.c0 || x.c1 || y.c0 || y.c1 (128 bytes), which is the
// same coordinate order snarkjs uses in its JSON (the Solidity exporter swaps it; we don't).
//
// Usage: bun near/zk/gen-vk.ts <verification_key.json> <out vk.rs>
import { readFileSync, writeFileSync } from 'node:fs'

const [vkPath, outPath] = process.argv.slice(2)
if (!vkPath || !outPath) throw new Error('usage: gen-vk.ts <verification_key.json> <out.rs>')

const vk = JSON.parse(readFileSync(vkPath, 'utf8'))
if (vk.protocol !== 'groth16' || vk.curve !== 'bn128') throw new Error('expected a bn128 Groth16 key')

const le32 = (dec: string): number[] => {
  let v = BigInt(dec)
  const out: number[] = []
  for (let i = 0; i < 32; i++) {
    out.push(Number(v & 0xffn))
    v >>= 8n
  }
  if (v !== 0n) throw new Error(`value does not fit in 32 bytes: ${dec}`)
  return out
}
const g1 = (p: string[]) => [...le32(p[0]), ...le32(p[1])]
const g2 = (p: string[][]) => [...le32(p[0][0]), ...le32(p[0][1]), ...le32(p[1][0]), ...le32(p[1][1])]
const arr = (bytes: number[]) => `[${bytes.join(', ')}]`

const ic: string[][] = vk.IC
const src = `// @generated by near/zk/gen-vk.ts from a snarkjs Groth16 verification key. Do not edit.
// Circuit: circuits/transaction.circom. Public inputs: root, publicAmount, extDataHash,
// inputNullifier[2], outputCommitment[2].

pub const N_PUBLIC: usize = ${vk.nPublic};

pub const ALPHA_G1: [u8; 64] = ${arr(g1(vk.vk_alpha_1))};
pub const BETA_G2: [u8; 128] = ${arr(g2(vk.vk_beta_2))};
pub const GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2))};
pub const DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2))};

pub const IC: [[u8; 64]; ${ic.length}] = [
${ic.map((p) => `    ${arr(g1(p))},`).join('\n')}
];
`
writeFileSync(outPath, src)
console.log(`wrote ${outPath} (nPublic=${vk.nPublic}, IC=${ic.length})`)
