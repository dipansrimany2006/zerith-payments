#!/usr/bin/env bash
# Compiles circuits/transaction.circom and runs a DEV Groth16 setup (one random contribution),
# then regenerates the contract's verifying key (near/contracts/pool/src/vk.rs).
#
# Not for production: mainnet needs a public multi-party phase-2 ceremony.
# Outputs go to build/ (gitignored) except vk.rs.
set -euo pipefail
cd "$(dirname "$0")/../.."

SNARK="node node_modules/snarkjs/build/cli.cjs" # snarkjs worker threads crash under Bun
PTAU=build/zk/powersOfTau28_hez_final_16.ptau
OUT=build/zk-groth16
mkdir -p build/circuits "$OUT"

# Hermez Powers of Tau, power 16 (64k constraints; the circuit has ~26k). Name and BLAKE2b-512 hash
# as published in the snarkjs README.
PTAU_URL="https://circom.info/powersOfTau28_hez_final_16.ptau"
PTAU_BLAKE2B="6a6277a2f74e1073601b4f9fed6e1e55226917efb0f0db8a07d98ab01df1ccf43eb0e8c3159432acd4960e2f29fe84a4198501fa54c8dad9e43297453efec125"
mkdir -p build/zk
[ -f "$PTAU" ] || curl -sSL --fail -o "$PTAU" "$PTAU_URL"
blake2b() { python3 -c "import hashlib,sys;h=hashlib.blake2b();f=open(sys.argv[1],'rb');[h.update(c) for c in iter(lambda:f.read(1<<20),b'')];print(h.hexdigest())" "$1"; }
if [ "$(blake2b "$PTAU")" != "$PTAU_BLAKE2B" ]; then
  echo "Powers of Tau hash does not match the published hash. Delete $PTAU and try again." >&2
  exit 1
fi

echo "1/4 compile"
.tools/circom circuits/transaction.circom --r1cs --wasm --sym -o build/circuits -l node_modules >/dev/null

echo "2/4 groth16 setup"
$SNARK groth16 setup build/circuits/transaction.r1cs "$PTAU" "$OUT/transaction_0000.zkey" >/dev/null

echo "3/4 dev contribution"
$SNARK zkey contribute "$OUT/transaction_0000.zkey" "$OUT/transaction.zkey" \
  --name="dev-$(date +%s)" -e="$(head -c 64 /dev/urandom | base64)" >/dev/null
rm "$OUT/transaction_0000.zkey"

echo "4/4 verifying key"
$SNARK zkey export verificationkey "$OUT/transaction.zkey" "$OUT/transaction_vk.json" >/dev/null
node near/zk/gen-vk.ts "$OUT/transaction_vk.json" near/contracts/pool/src/vk.rs

echo "5/5 browser proving files (public/zk) + pinned hashes (src/lib/zk-artifacts.ts)"
mkdir -p public/zk
cp build/circuits/transaction_js/transaction.wasm public/zk/transaction.wasm
cp "$OUT/transaction.zkey" public/zk/transaction.zkey
sha() { shasum -a 256 "$1" | cut -d' ' -f1; }
cat > src/lib/zk-artifacts.ts <<EOF
// GENERATED by near/zk/setup.sh. Do not edit by hand.
// Proving files for circuits/transaction.circom (Groth16, powersOfTau28_hez_final_16.ptau).
export const ZK_WASM = { url: '/zk/transaction.wasm', sha256: '$(sha public/zk/transaction.wasm)' }
export const ZK_ZKEY = { url: '/zk/transaction.zkey', sha256: '$(sha public/zk/transaction.zkey)' }
EOF

ls -l "$OUT" public/zk
