// Emits circomlib Poseidon(2) constants (width 3) as compile-time arkworks field elements,
// taken from poseidon-lite, the same implementation the frontend and fixture use.
//
// Usage: node near/zk/gen-poseidon.ts <out poseidon_constants.rs>
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

// poseidon-lite does not export these subpaths, so load them by file path.
const require = createRequire(import.meta.url)
const pkg = dirname(require.resolve('poseidon-lite'))
const unstringify = require(join(pkg, 'poseidon/unstringify.js')).default
const { C, M } = unstringify(require(join(pkg, 'constants/2.js')).default) as { C: bigint[]; M: bigint[][] }

const [outPath] = process.argv.slice(2)
if (!outPath) throw new Error('usage: gen-poseidon.ts <out.rs>')

const T = 3
const ROUNDS = 8 + 57
if (C.length !== ROUNDS * T) throw new Error(`unexpected C length ${C.length}`)
if (M.length !== T) throw new Error(`unexpected M size ${M.length}`)

const fr = (v: bigint) => {
  const limbs: string[] = []
  for (let i = 0; i < 4; i++) limbs.push(`0x${((v >> BigInt(64 * i)) & 0xffffffffffffffffn).toString(16)}`)
  return `Fr::new(BigInt::new([${limbs.join(', ')}]))`
}

const src = `// @generated by near/zk/gen-poseidon.ts from poseidon-lite (circomlib Poseidon, t = 3). Do not edit.
use ark_bn254::Fr;
use ark_ff::BigInt;

pub const T: usize = ${T};
pub const FULL_ROUNDS: usize = 8;
pub const PARTIAL_ROUNDS: usize = 57;

pub const C: [Fr; ${C.length}] = [
${C.map((c) => `    ${fr(c)},`).join('\n')}
];

pub const M: [[Fr; ${T}]; ${T}] = [
${M.map((row) => `    [${row.map(fr).join(', ')}],`).join('\n')}
];
`
writeFileSync(outPath, src)
console.log(`wrote ${outPath} (${C.length} round constants)`)
